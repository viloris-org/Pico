// ── Wire format helpers ──

/// Maximum message body length (1 MB).
pub const MAX_BODY_LENGTH: usize = 1024 * 1024;

/// Minimum header size: 4-byte length + 1-byte type.
pub const HEADER_SIZE: usize = 5;

/// String on the wire: u32 (big-endian length) + UTF-8 bytes.
pub const MAX_STRING_LENGTH: usize = 64 * 1024;

pub const MAX_ATTACHMENT_LENGTH: usize = 8 * 1024 * 1024;

/// Payload of cancel_request: an unpredictable credential unique within the
/// Connection lifetime, generated by the Server after startup and delivered to
/// the client in the HELLO_OK response.
pub const CANCEL_CREDENTIAL_LENGTH: usize = 16;
pub const MAX_ATTACHMENT_CHUNK_LENGTH: usize = 256 * 1024;
pub const PAYLOAD_DIGEST_LENGTH: usize = 32;

pub const Modality = enum(u8) {
    text = 1,
    image = 2,
    audio = 3,
    video = 4,
    sensor = 5,
    other = 6,
};

/// A scalar value for a document field in the official RunaDB Client. Text is
/// borrowed by the caller and owned by it for the duration of the request.
pub const DocumentValue = union(enum) {
    null,
    int: i64,
    text: []const u8,
    bool: bool,
};

/// One field of a `document_insert` request. `path` is a dotted path (for
/// example `author.name`).
pub const DocumentField = struct {
    path: []const u8,
    value: DocumentValue,
};
