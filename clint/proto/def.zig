//! RunaDB Wire Protocol — shared message type definitions.
//! Used by both RunaDB Server (src/net/runadb.zig) and RunaDB Client (clint/).
//! Version: v3.0 (development contract; incompatible with the retired SQL endpoint).

/// The major version negotiated in HELLO. A peer whose major differs is
/// rejected with HELLO_ERROR before any v3-only framing is parsed, so a v2
/// peer can never misparse the trailing credential that v3 HELLO_OK appends.
pub const PROTOCOL_VERSION_MAJOR: u16 = 3;
pub const PROTOCOL_VERSION_MINOR: u16 = 0;
pub const IR_FORMAT_VERSION: u16 = 4;

/// HELLO_OK (server -> client) layout — the shared parsing contract. The body
/// is a length-prefixed server version string, then exactly
/// CANCEL_CREDENTIAL_LENGTH bytes of cancellation credential, in that order
/// with nothing after. The Server writes them in this order (sendHelloOk in
/// src/net/runadb.zig) and the Client reads them in this order (readMessage in
/// clint/zig/codec.zig), so both must change together if this layout does.

/// Message type identifiers.
pub const Type = enum(u8) {
    /// Client → Server: initiates connection, carries protocol version.
    hello = 0x01,
    /// Server → Client: accepts connection; carries the server version string
    /// followed by the Connection's CANCEL_CREDENTIAL_LENGTH-byte credential.
    hello_ok = 0x02,
    /// Server → Client: rejects connection with a reason.
    hello_error = 0x03,

    /// Client → Server: submits Runa Flow source for parse, binding, and execution.
    flow_source = 0x10,
    /// Client → Server: submits canonical Runa Query IR.
    flow_ir = 0x15,
    /// Server → Client: column metadata for result rows.
    row_description = 0x11,
    /// Server → Client: a single row of data.
    row_data = 0x12,
    /// Server → Client: statement finished successfully.
    command_complete = 0x13,
    /// Server → Client: statement failed.
    server_error = 0x14,

    /// Client -> Server attachment staging for an `observe` IR request.
    attachment_begin = 0x20,
    attachment_chunk = 0x21,
    attachment_finish = 0x22,
    attachment_abort = 0x23,

    /// Server -> Client bounded payload stream for `read_evidence_payload`.
    payload_begin = 0x28,
    payload_chunk = 0x29,
    payload_finish = 0x2A,

    /// Client -> Server: requests cooperative cancellation of the statement
    /// currently executing on the Connection named by the credential.
    /// Fire-and-forget: the Server never replies to a well-formed request.
    /// Unknown, mismatched, closed, or expired credentials finish as a no-op.
    /// A malformed payload is a protocol error: the Server replies with CN1001
    /// and closes the Connection.
    cancel_request = 0x30,

    /// Either side: clean close.
    goodbye = 0xFF,

    _,
};

// ── Message payload structures ──

/// Payload of hello (client → server).
pub const Hello = packed struct {
    version_major: u16,
    version_minor: u16,
};

/// Payload of hello_ok (server → client).
/// Followed by a length-prefixed server version string.
/// Payload of hello_error (server → client).
/// Followed by a length-prefixed reason string.
/// Payload of flow_source (client → server).
/// Followed by a length-prefixed Runa Flow source string.
///
/// Payload of flow_ir (client → server).
/// `u16` big-endian IR format version followed by canonical IR bytes.
/// Payload of row_description (server → client).
pub const RowDescription = packed struct {
    column_count: u16,
};
/// For each column, a length-prefixed name string follows.
/// Payload of row_data (server → client).
pub const RowData = packed struct {
    column_count: u16,
};
/// For each column, a null flag (u8, 0=not null, 1=null) followed by a
/// length-prefixed text value (omitted if null).
/// Payload of command_complete (server → client).
/// Followed by a length-prefixed tag string (e.g. "INSERT 0 1", "SELECT 3").
pub const CommandComplete = packed struct {
    affected_rows: u64,
};

/// Payload of error (server → client).
/// Followed by severity byte, then length-prefixed code and message strings.
pub const Error = packed struct {
    severity: u8, // 0=INFO, 1=WARNING, 2=ERROR, 3=FATAL
};

